"""Finalize the separate report and verify preservation; run no molecular calculations."""
import json,hashlib,re,ast
from pathlib import Path
from datetime import datetime,timezone
ROOT=Path(__file__).resolve().parent
read=lambda p:json.loads(p.read_text(encoding="utf-8-sig"))
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
def write(name,obj):(ROOT/name).write_text(json.dumps(obj,indent=2,allow_nan=False)+"\n",encoding="utf-8")
p=read(ROOT/"protocol.json")
primary=read(ROOT/"comparison-results.json")
follow=read(ROOT/"response-check/verification-results.json")
follow_protocol=read(ROOT/"response-check/protocol.json")
assert sha(ROOT/"comparison-results.json")==follow_protocol["parent_results_sha256"]
assert sha(ROOT/"protocol.json")==follow_protocol["parent_protocol_sha256"]
assert sha(ROOT/"analyze_comparison.py")==primary["analyzer_sha256"]
assert sha(ROOT/"response-check/run_response_check.py")==follow["runner_sha256"]
assert sha(ROOT/"response-check/protocol.json")==follow["protocol_sha256"]
assert follow["all_validation_checks_pass"]
assert all(c["passes"] for c in follow["numerical_checks"])
assert primary["primary_H2O_outcome"]=="FAIL" and not follow["H2O_followup_gap_inside_original_interval"]
for row in follow["evaluations"]:
    assert sha(ROOT/"response-check"/row["file"])==row["sha256"]
report=(ROOT/"primary-report.md").read_text(encoding="utf-8-sig")
h2=follow["results"]["H2O"];d2=follow["results"]["D2O"]
maxres=next(c["value"] for c in follow["numerical_checks"] if c["name"]=="maximum true response residual")
additional=f"""
The original gradient-response solver emitted 91 warnings: its largest reported residual was 1.024e-8 against its requested 1e-9 tolerance. We then [registered a separate numerical check](response-check/protocol.json), keeping the physical method, saved geometry and gap rule fixed. It used a different linear solver for the same response equation and checked that equation's residual directly. All six follow-up controls passed across 19 additional gradient evaluations, with a maximum response residual of {maxres:.3e}. The [follow-up result](response-check/verification-results.json) was H2O **{h2["gap_cm1"]:.6f} cm^-1**, a change of **{h2["gap_change_cm1"]:.6f} cm^-1**; D2O changed by {d2["gap_change_cm1"]:.6f} cm^-1. These changes do not alter the original FAIL. The original 91 evaluations, their warnings and the primary result remain intact.

The second geometry optimization reported precision loss. Its final maximum Cartesian gradient was 8.85e-8 Eh/bohr, within the predeclared 5e-7 limit, and its geometry and energy agreed with the first start within the recorded limits. The primary result uses the first start, as registered.
"""
anchor="\nFor D2O, the new harmonic prediction"
assert anchor in report
report=report.replace(anchor,"\n"+additional+anchor,1)
report=report.replace(
 "This comparison tests the specified MP2 method and finite basis for this molecule. It does not isolate which xTB term is physically inaccurate, establish basis-set convergence, or validate a liquid-water simulation. Those are separate questions.",
 "The finding applies to this gas-phase molecule and fixed basis. The specific source of xTB's physical error and the effect of increasing MP2's basis size remain untested.")
report=report.replace(
 "Generated by Codex under the user's direction.",
 "After the primary analysis and the response check, running finalize_report.py incorporates that follow-up without replacing the primary result. [Artifact verification](verification.json) records preservation and path checks.\n\nGenerated by Codex under the user's direction.")
(ROOT/"README.md").write_text(report,encoding="utf-8")
repo=ROOT.parent/"mysources-stretch-gap-publication"
protected=p["preservation"]["protected_published_files_sha256"]
for name,digest in protected.items():
    content=(repo/name).read_bytes()
    if name=="README.md":content=content.replace(b"\r\n",b"\n")
    assert hashlib.sha256(content).hexdigest()==digest,name
for f in ROOT.rglob("*.py"):
    if "scratch" not in f.parts and "plot-cache" not in f.parts:
        ast.parse(f.read_text(encoding="utf-8-sig"))
excluded=["preflight-console.txt","scratch/","plot-cache/","response-check/scratch/"]
files=[f for f in ROOT.rglob("*") if f.is_file()
       and f.relative_to(ROOT).as_posix()!="preflight-console.txt"
       and not any(x in ["scratch","plot-cache","__pycache__"] for x in f.relative_to(ROOT).parts)
       and f.name not in ["verification.json","addition-checksums.json"]]
pattern=re.compile(rb"(?i)\b[A-Z]:[\\/]|file:[/]{2,3}(?=[A-Za-z/])|/(?:Users|home|mnt|tmp|private/var)/")
hits=[f.relative_to(ROOT).as_posix() for f in files if pattern.search(f.read_bytes())]
assert not hits,hits
v={"verified_at_utc":datetime.now(timezone.utc).isoformat(),
   "primary_outcome":"FAIL","new_method":"all-electron RMP2/cc-pVTZ",
   "primary_H2O_gap_cm1":primary["primary_results"]["H2O"]["gap_cm1"],
   "registered_pass_interval_cm1":[101,121],
   "primary_numerical_controls":{"passed":36,"total":36},
   "response_followup_controls":{"passed":6,"total":6},
   "primary_energy_gradient_evaluations":91,"separate_followup_gradient_evaluations":19,
   "primary_results_sha256":sha(ROOT/"comparison-results.json"),
   "followup_results_sha256":sha(ROOT/"response-check/verification-results.json"),
   "primary_result_preserved":True,"gap_mark_and_method_unchanged":True,
   "protected_published_files_count":len(protected),"protected_published_files_sha256":protected,
   "path_scan":{"candidate_artifacts_scanned":len(files),"matches":[],"excluded_private_runtime_artifacts":excluded,
                "exclusion_reason":"The raw preflight traceback and runtime caches may contain local folder paths. They are retained locally for provenance and excluded from any publication candidate."},
   "diagram_visually_checked":True,
   "new_Lean_check":False,"published_to_github":False}
write("verification.json",v)
files.append(ROOT/"verification.json")
assert not pattern.search((ROOT/"verification.json").read_bytes())
write("addition-checksums.json",{"scope":"Local diagnostic artifacts; not a publication receipt",
      "excluded_private_runtime_artifacts":excluded,
      "files":{f.relative_to(ROOT).as_posix():sha(f) for f in sorted(files)}})
print(json.dumps({"primary_outcome":"FAIL","primary_gap_cm1":primary["primary_results"]["H2O"]["gap_cm1"],
                  "followup_gap_change_cm1":h2["gap_change_cm1"],"protected_xTB_files_unchanged":len(protected),
                  "artifact_path_matches":0,"artifacts_hashed":len(files)}))
